#!/bin/sh
# Regenerate reparse_ref_body.inc from the corrected C validator, VERBATIM.
# The differential harness compiles these three functions over the portable shim,
# so it runs on any host toolchain without building the whole ntfslib; the struct
# size asserts in the shim catch ABI drift. After editing reparse.cpp, rerun this
# and commit the diff so the copy never diverges silently. Ranges are derived from
# the function signatures, so upstream edits do not silently shift them.
set -eu
HERE="$(cd "$(dirname "$0")" && pwd)"
SRC="$HERE/../../src/filerecord/read/reparse.cpp"
OUT="$HERE/reparse_ref_body.inc"
[ -f "$SRC" ] || { echo "source not found: $SRC" >&2; exit 2; }

ln() { grep -n "$1" "$SRC" | head -1 | cut -d: -f1; }   # first line matching regex
hdr=$(ln '^typedef struct _NTFS_SYMLINK_REPARSE_HEADER')
val=$(ln '^NtfsValidateReparseBuffer(')
isn=$(ln '^IsNameRangeValid(')
wof=$(ln '^FileRecord::IsWofBacked')
par=$(ln '^NtfsParseNameSurrogateReparsePoint(')
cmp=$(ln '^NtfsCompareReparseKeys(')
# block end = two lines before the NEXT declaration's name line (its return-type
# line + the blank separator). Each function's return type sits one line above its
# name line, so a block starts at name-1.
block() { sed -n "$(( $1 - 1 )),$(( $2 - 3 ))p" "$SRC"; }

{
  echo "/* Extracted VERBATIM from ntfslib_new src/filerecord/read/reparse.cpp."
  echo " * Regenerated by gen-ref-body.sh (signature-anchored ranges):"
  echo " * local reparse headers, NtfsValidateReparseBuffer, IsNameRangeValid,"
  echo " * NtfsParseNameSurrogateReparsePoint. Edit reparse.cpp, not this file. */"
  echo
  sed -n "${hdr},$(( val - 2 ))p" "$SRC"   # the two local headers + static_asserts
  echo
  block "$val" "$isn"                       # NtfsValidateReparseBuffer
  echo
  block "$isn" "$wof"                        # IsNameRangeValid
  echo
  block "$par" "$cmp"                        # NtfsParseNameSurrogateReparsePoint
} > "$OUT"
echo "wrote $OUT"
